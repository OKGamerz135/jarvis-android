package dev.jarvis.assistant.chat

import java.io.File
import java.io.IOException

interface ChatStorage {
    fun save(conversation: Conversation)
    fun load(id: String): Conversation?
    fun list(): List<ConversationSummary>
    fun delete(id: String)
}

/** One JSON file per conversation, in app-private storage. Writes go to a temp file first, then replace. */
class FileChatStorage(private val dir: File, private val maxConversations: Int = 200) : ChatStorage {
    private val lock = Any()

    private fun fileFor(id: String) = File(dir, safeName(id) + ".json")

    /** Ids are generated by the app, but never let one escape the folder. */
    private fun safeName(id: String) = id.filter { it.isLetterOrDigit() || it == '-' || it == '_' }.ifEmpty { "x" }

    override fun save(conversation: Conversation) {
        synchronized(lock) {
            dir.mkdirs()
            val target = fileFor(conversation.id)
            val tmp = File(dir, target.name + ".tmp")
            tmp.writeText(ChatCodec.encode(conversation))
            if (!tmp.renameTo(target)) {
                target.delete()
                if (!tmp.renameTo(target)) throw IOException("Couldn't save the conversation")
            }
            prune()
        }
    }

    override fun load(id: String): Conversation? = synchronized(lock) {
        val f = fileFor(id)
        if (!f.exists()) null else try { ChatCodec.decode(f.readText()) } catch (e: IOException) { null }
    }

    override fun list(): List<ConversationSummary> = synchronized(lock) {
        val files = dir.listFiles { f -> f.name.endsWith(".json") } ?: return emptyList()
        files.mapNotNull { f ->
            try { ChatCodec.decode(f.readText()) } catch (e: IOException) { null }
        }
            .filter { !it.isEmpty }
            .map { ConversationSummary(it.id, it.title, it.updatedAt, it.messages.size) }
            .sortedByDescending { it.updatedAt }
    }

    override fun delete(id: String) {
        synchronized(lock) { fileFor(id).delete() }
    }

    /** Keeps the newest [maxConversations]; older ones are deleted so storage can't grow forever. */
    private fun prune() {
        val all = list()
        for (old in all.drop(maxConversations)) fileFor(old.id).delete()
    }
}
